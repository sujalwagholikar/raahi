"""Generate all public connection defaults from config/connection.json."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
c = json.loads((root / 'config/connection.json').read_text())
url, key, api = c['supabaseUrl'], c['supabasePublishableKey'], c.get('apiBase', '')
assert url.startswith('https://') and key.startswith(('sb_publishable_', 'eyJ'))
assert not api or api.startswith(('https://', 'http://localhost'))
(root / 'dist/config.js').write_text('window.RAAHI_CONFIG = ' + json.dumps({'apiBase': api, 'supabaseUrl': url, 'supabaseAnonKey': key}, indent=2) + ';\n')
(root / 'android/connection.properties').write_text('# Public defaults. Generated by scripts/sync-connection.py\nAUTH_URL=' + url + '\nANON_KEY=' + key + '\nAPI_BASE=' + api + '\n')
(root / 'internal/config/public.go').write_text('// Code generated by scripts/sync-connection.py; DO NOT EDIT.\npackage config\n\nconst SupabaseURL = ' + json.dumps(url) + '\nconst SupabasePublicKey = ' + json.dumps(key) + '\n')
(root / '.env.example').write_text('# Public project connection. Environment values override compiled defaults.\nSUPABASE_URL=' + url + '\nSUPABASE_ANON_KEY=' + key + '\n# For a separately hosted frontend, use its exact origin:\nALLOWED_ORIGINS=https://raahi-mobility-hub.mirchikadesitadka.chatgpt.site\n')
vercel = json.loads((root / 'vercel.json').read_text())
vercel.setdefault('env', {}).update({'SUPABASE_URL': url, 'SUPABASE_ANON_KEY': key, 'ALLOWED_ORIGINS': 'https://raahi-mobility-hub.mirchikadesitadka.chatgpt.site'})
(root / 'vercel.json').write_text(json.dumps(vercel, indent=2) + '\n')
print('Public connection defaults synchronized across web, Android, Go and Vercel.')
